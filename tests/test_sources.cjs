const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const lib = require('../assets/sources.js');
const sample = '\uFEFF"id","name","url","kind","checked_on"\r\n"S01","Amazon, Seller","https://example.com/a","official","2026-11-05"\r\n"B01","Brand ""A""","https://example.com/b","public case","2026-10-01"\r\n';
const rows = lib.parseCsv(sample);
assert.equal(rows.length, 2);
assert.equal(rows[0].name, 'Amazon, Seller');
assert.equal(rows[1].name, 'Brand "A"');
assert.throws(() => lib.parseCsv('"id","oops"\n'), /表头/);
assert.throws(() => lib.parseCsv(sample + '"S03","incomplete"\n'), /列数/);
assert.equal(lib.safeUrl('javascript:alert(1)'), null);
assert.equal(lib.safeUrl('http://example.com'), null);
assert.equal(lib.safeUrl('https://example.com/path'), 'https://example.com/path');
const now = new Date('2026-11-20T12:00:00Z');
assert.equal(lib.daysSince('2026-11-05', now), 15);
assert.equal(lib.filterRows(rows, 'amazon', '', false, now).length, 1);
assert.equal(lib.filterRows(rows, '', 'official', false, now).length, 1);
assert.equal(lib.filterRows(rows, '', '', true, now).length, 1);
assert.equal(lib.filterRows(rows, '', 'official', true, now).length, 0);
assert.match(lib.asText(rows), /历史核验日不代表今天有效/);
assert.match(lib.asText(rows), /AIPMAndy/);
assert.match(lib.asText(rows), /2026-11-05/);
assert.doesNotMatch(lib.asText(rows), /已经核验为有效/);
const repo = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(repo, 'research/source-register.csv'), 'utf8');
const live = lib.parseCsv(source);
assert.ok(live.length >= 29, 'historical ledger must remain complete');
assert.equal(new Set(live.map(x => x.id)).size, live.length, 'source IDs must be unique');
assert.ok(live.every(x => x.checked_on && x.url.startsWith('https://')), 'dates and URLs required');
console.log('PASS: CSV quoting/BOM/CRLF, safe URLs, filters, TXT provenance, ' + live.length + ' real source rows');
